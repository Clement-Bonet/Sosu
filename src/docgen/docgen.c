/* docgen: the reference of the public API of `core` and `std` (docs/REFERENCE.md), made from
   the sources by src/lib/docgen.c. Run by `make doc`.
   Usage: docgen OUT.md FILE.sosu... (each FILE in lib/<package>/src/ or packages/<package>/src/) */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "common.h"
#include "docgen.h"

static char *read_text(const char *path) {
    FILE *f = fopen(path, "rb");
    if (!f) {
        fprintf(stderr, "docgen: cannot read `%s`\n", path);
        exit(1);
    }
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    rewind(f);
    char *text = sosu_alloc((size_t)size + 1);
    size_t read = fread(text, 1, (size_t)size, f);
    fclose(f);
    text[read] = '\0';
    return text;
}

/* `std.io` from `lib/std/src/io.sosu`. */
static char *module_of(const char *path) {
    char copy[1024];
    snprintf(copy, sizeof copy, "%s", path);
    for (char *c = copy; *c; c++) {
        if (*c == '\\') *c = '/';
    }
    char *file = strrchr(copy, '/');
    file = file ? file + 1 : copy;
    char *dot = strrchr(file, '.');
    if (dot) *dot = '\0';
    char *src = strstr(copy, "/src/");
    const char *package = "?";
    if (src) {
        *src = '\0';
        char *slash = strrchr(copy, '/');
        package = slash ? slash + 1 : copy;
    }
    return sosu_format("%s.%s", package, file);
}

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "usage: docgen OUT.md FILE.sosu...\n");
        return 2;
    }
    FILE *out = fopen(argv[1], "wb"); /* "\n" line ends on every system */
    if (!out) {
        fprintf(stderr, "docgen: cannot write `%s`\n", argv[1]);
        return 1;
    }
    size_t count = (size_t)(argc - 2);
    DocSource *sources = sosu_alloc(count * sizeof *sources);
    for (size_t f = 0; f < count; f++) {
        sources[f].module = module_of(argv[f + 2]);
        sources[f].text = read_text(argv[f + 2]);
    }
    docgen_write(out,
                 "# Sosu library reference\n\n"
                 "The public API of the `core` and `std` packages, and of the packages of spec 8.3: what is `pub`,\n"
                 "with the comments written above it. Generated by `make doc` (src/docgen) from lib/ and packages/;\n"
                 "do not edit. The language itself is described in [SPEC.md](SPEC.md).\n\n",
                 sources, count);
    fclose(out);
    for (size_t f = 0; f < count; f++) {
        free((char *)sources[f].module);
        free((char *)sources[f].text);
    }
    free(sources);
    return 0;
}
